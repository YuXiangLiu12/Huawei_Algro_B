function summary=q1_run_experiments(root,selected,level)
% Structural runs use identical parameters. Refit before model-selection claims.
if nargin<1,root=fileparts(fileparts(mfilename('fullpath')));end
if nargin<2,selected=string.empty;end
if nargin<3,level='coarse';end
base=q1_config();
specs={ ...
    'M1_repaired',struct(); ...
    'legacy_272',struct('clFrozenWater',false); ...
    'M0_no_ice',struct('iceEnabled',false); ...
    'A1_fixed_conductivity_water',struct('freezeConductivityLambda',true); ...
    'A2_no_ice_feedback',struct('iceFeedback',false); ...
    'A3_no_PEM_freeze',struct('pemFreeze',false); ...
    'A4_no_latent_heat',struct('phaseHeat',false); ...
    'S1_small_des_finite',struct('kdes',.001,'kabs',1,'vaporBoundary','finite_flow'); ...
    'S1_small_des_dry',struct('kdes',.001,'kabs',1,'vaporBoundary','dry'); ...
    'S1_large_des_finite',struct('kdes',1,'kabs',.001,'vaporBoundary','finite_flow'); ...
    'S1_large_des_dry',struct('kdes',1,'kabs',.001,'vaporBoundary','dry'); ...
    'S2_liquid_route',struct('liquidRoute',true); ...
    'S3_mao_resistance',struct('voltageResistance','mao_cathode_only'); ...
    'S4_cold_conductivity',struct('conductivity','cold2222'); ...
    'S5_closed_vapor',struct('vaporBoundary','closed'); ...
    'S6_liquid_migration',struct('liquidRoute',true,'liquidMigration',true); ...
    'S7_local_average_reaction',struct('reactionClosure','local_average'); ...
    'S8_hydrated_kinetics',struct('reactionClosure','parallel_active', ...
        'kineticHydrationExponent',2); ...
    'S9_delayed_nucleation',struct('freezingClosure','delayed_nucleation', ...
        'liquidMigration',true); ...
    'ice_partition_pore_first',struct('icePartition','pore_first'); ...
    'input_area_310',struct('inputArea_cm2',310)};
rows=cell(0,12);
for i=1:size(specs,1)
    name=string(specs{i,1});
    if ~isempty(selected) && ~any(name==string(selected)),continue;end
    c=base; fields=fieldnames(specs{i,2});
    for z=1:numel(fields),c.(fields{z})=specs{i,2}.(fields{z});end
    [cases,~]=q1_read_data(root,c);
    for k=1:2
        run=q1_simulate(cases(k),c,level);
        vr=NaN; tr=NaN; ice=NaN; sat=NaN; liq=NaN; ew=NaN; eE=NaN;
        if isfield(run,'balance')
            ew=run.balance.ew; eE=run.balance.eE;
        end
        if isfield(run,'obs')
            ice=run.obs(end).ice_volume_max;
            sat=run.obs(end).ice_saturation_max;
            liq=max([run.obs.liquid_saturation_max]);
            if numel(run.obs)==numel(cases(k).t)
                vr=sqrt(mean(([run.obs.V_sim]'-cases(k).V_exp).^2));
                tr=sqrt(mean(([run.obs.T_seven_C]'-cases(k).T_exp_C).^2));
            end
        end
        rows(end+1,:)={name,string(cases(k).name),string(run.status), ...
            string(run.event),run.t_end,vr,tr,ice,sat,liq,ew,eE}; %#ok<AGROW>
    end
end
summary=cell2table(rows,'VariableNames',{'experiment','case_name','status', ...
    'event','t_end_s','V_RMSE','T_RMSE_C','ice_absolute_final', ...
    'ice_saturation_final','liquid_saturation_max','water_error','energy_error'});
folder=fullfile(root,'results','experiments');
if ~isfolder(folder),mkdir(folder);end
writetable(summary,fullfile(folder,'structural_summary.csv'));
end
